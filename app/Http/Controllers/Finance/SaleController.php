    /**
     * Confirm a pending storefront order: re-check stock, deduct it,
     * and mark the sale as completed.
     */
    public function confirm(Sale $sale)
    {
        abort_unless($sale->user_id === auth()->id(), 403);

        if ($sale->status !== 'pending' || $sale->order_source !== 'storefront') {
            return back()->with('error', 'Only pending storefront orders can be confirmed.');
        }

        $insufficient = [];
        foreach ($sale->salesDetails as $detail) {
            $product = $detail->product;
            if (!$product || !$product->hasSufficientStock($detail->quantity)) {
                $insufficient[] = sprintf(
                    '%s (butuh %d, tersedia %d)',
                    $product?->name ?? 'Produk dihapus',
                    $detail->quantity,
                    $product?->stock_quantity ?? 0
                );
            }
        }

        if (!empty($insufficient)) {
            return back()
                ->with('error', 'Stok tidak mencukupi untuk: ' . implode('; ', $insufficient))
                ->with('insufficient_items', $insufficient);
        }

        DB::transaction(function () use ($sale) {
            foreach ($sale->salesDetails as $detail) {
                $product = $detail->product;
                if (!$product->reduceStock($detail->quantity)) {
                    throw new \Exception("Failed to reduce stock for product: {$product->name}");
                }
            }

            $sale->update(['status' => 'completed']);
        });

        Cache::forget('pending_storefront_count_' . $sale->user_id);

        return redirect()->route('finance.sales.show', $sale)
            ->with('success', 'Pesanan dikonfirmasi dan stok dipotong.');
    }

    /**
     * Cancel a pending storefront order. No stock movement
     * because the confirmation step never ran.
     */
    public function cancel(Request $request, Sale $sale)
    {
        abort_unless($sale->user_id === auth()->id(), 403);

        if ($sale->status !== 'pending' || $sale->order_source !== 'storefront') {
            return back()->with('error', 'Only pending storefront orders can be cancelled.');
        }

        $request->validate([
            'rejection_reason' => 'required|string|max:1000',
        ]);

        $sale->update([
            'status' => 'cancelled',
            'rejection_reason' => $request->input('rejection_reason'),
        ]);

        Cache::forget('pending_storefront_count_' . $sale->user_id);

        return redirect()->route('finance.sales.show', $sale)
            ->with('success', 'Pesanan dibatalkan.');
    }
}


    /**
     * Store a newly created resource in storage.
     */
    public function store(Request $request)
    {
        $validated = $request->validate([

            'sale_date' => 'required|date',
            'payment_method' => 'required|in:cash,credit_card,debit_card,bank_transfer,e_wallet,qris',
            'notes' => 'nullable|string',
            'products' => 'required|array|min:1',
            'products.*.product_id' => 'required|exists:products,id',
            'products.*.quantity' => 'required|integer|min:1',
            'products.*.unit_price' => 'required|numeric|min:0',
            'products.*.discount_percentage' => 'nullable|numeric|min:0|max:100',
        ]);

        // Validate stock availability before processing
        foreach ($validated['products'] as $item) {
            $product = Product::find($item['product_id']);
            if (!$product || !$product->hasSufficientStock($item['quantity'])) {
                return back()->withErrors([
                    'products' => "Insufficient stock for product: " . ($product ? $product->name : 'Unknown') . ". Available: " . ($product ? $product->stock_quantity : 0) . ", Required: " . $item['quantity']
                ])->withInput();
            }
        }

        DB::transaction(function () use ($validated) {
            // Calculate totals first
            $subtotalAmount = 0;
            $totalDiscount = 0;

            foreach ($validated['products'] as $item) {
                $lineTotal = $item['quantity'] * $item['unit_price'];
                $discountPercentage = $item['discount_percentage'] ?? 0;
                $itemDiscount = $lineTotal * ($discountPercentage / 100);
                $subtotalAmount += $lineTotal - $itemDiscount;
                $totalDiscount += $itemDiscount;
            }

            $taxAmount = $subtotalAmount * 0.1; // 10% tax
            $totalAmount = $subtotalAmount + $taxAmount;

            // Create sale with all required fields (invoice number auto-generated by model)
            $sale = Sale::create([
                'customer_id' => null,
                'sale_date' => $validated['sale_date'],
                'subtotal' => $subtotalAmount,
                'tax_amount' => $taxAmount,
                'discount_amount' => $totalDiscount,
                'total_amount' => $totalAmount,
                'payment_method' => $validated['payment_method'],
                'status' => 'completed',
                'notes' => $validated['notes'],
            ]);

            // Create sale details and update stock
            foreach ($validated['products'] as $item) {
                $lineTotal = $item['quantity'] * $item['unit_price'];
                $discountPercentage = $item['discount_percentage'] ?? 0;
                $discountAmount = $lineTotal * ($discountPercentage / 100);

                SalesDetail::create([
                    'sale_id' => $sale->id,
                    'product_id' => $item['product_id'],
                    'quantity' => $item['quantity'],
                    'unit_price' => $item['unit_price'],
                    'discount_percentage' => $discountPercentage,
                    'discount_amount' => $discountAmount,
                    'line_total' => $lineTotal - $discountAmount,
                ]);

                // Safely update product stock
                $product = Product::find($item['product_id']);
                if (!$product->reduceStock($item['quantity'])) {
                    throw new \Exception("Failed to reduce stock for product: {$product->name}");
                }
            }


        });

        return redirect()->route('finance.sales.index')
            ->with('success', 'Sale created successfully.');
    }

    /**
     * Display the specified resource.
     */
    public function show(Sale $sale)
    {
        // Load sales details with product (including soft deleted products)
        $sale->load(['salesDetails' => function ($query) {
            $query->with(['product' => function ($q) {
                $q->withTrashed(); // Include soft deleted products
            }]);
        }]);
        
        // Get current user's business profile for payment info display
        $businessProfile = auth()->user()->businessProfile;
        
        return view('finance.sales.show', compact('sale', 'businessProfile'));
    }


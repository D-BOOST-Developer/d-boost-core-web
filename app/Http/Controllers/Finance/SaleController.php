    /**
     * Update the specified resource in storage.
     */
    public function update(Request $request, Sale $sale)
    {
        $validated = $request->validate([

            'sale_date' => 'required|date',
            'payment_method' => 'required|in:cash,credit_card,debit_card,bank_transfer,e_wallet,qris',
            'status' => 'required|in:pending,completed,cancelled,refunded',
            'notes' => 'nullable|string',
        ]);

        $sale->update($validated);

        return redirect()->route('finance.sales.show', $sale)
            ->with('success', 'Sale updated successfully.');
    }

    /**
     * Remove the specified resource from storage.
     */
    public function destroy(Sale $sale)
    {
        DB::transaction(function () use ($sale) {
            // Restore product stock
            foreach ($sale->salesDetails as $detail) {
                $product = Product::find($detail->product_id);
                if ($product) {
                    $product->increaseStock($detail->quantity);
                }
            }



            // Delete sale (soft delete)
            $sale->delete();
        });

        return redirect()->route('finance.sales.index')
            ->with('success', 'Sale deleted successfully.');
    }


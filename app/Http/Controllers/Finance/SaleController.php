class SaleController extends Controller
{
    /**
     * Display a listing of the resource.
     */
    public function index(Request $request)
    {
        $query = Sale::with(['salesDetails.product']);

        // Search functionality
        if ($request->filled('search')) {
            $search = $request->search;
            $query->where('invoice_number', 'like', "%{$search}%");
        }



        // Status filter
        if ($request->filled('status')) {
            $query->where('status', $request->status);
        }

        // Order source filter (walk_in vs storefront)
        if ($request->filled('order_source')) {
            $query->where('order_source', $request->order_source);
        }

        // Date range filter
        if ($request->filled('date_from')) {
            $query->whereDate('sale_date', '>=', $request->date_from);
        }
        if ($request->filled('date_to')) {
            $query->whereDate('sale_date', '<=', $request->date_to);
        }

        // Payment method filter
        if ($request->filled('payment_method')) {
            $query->where('payment_method', $request->payment_method);
        }

        $sales = $query->orderBy('sale_date', 'desc')->paginate(15);
        return view('finance.sales.index', compact('sales'));
    }


<?php

namespace App\Http\Controllers\Finance;

use App\Http\Controllers\Controller;
use App\Models\Sale;
use App\Models\Customer;
use App\Models\Product;
use App\Models\SalesDetail;
use App\Models\UserBusinessProfile;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

class SaleController extends Controller
{
    /**
     * Display a listing of the resource.
     */
    public function index(Request $request)
    {
        $query = Sale::with(['customer', 'salesDetails.product']);

        // Search functionality
        if ($request->filled('search')) {
            $search = $request->search;
            $query->where(function ($q) use ($search) {
                $q->where('invoice_number', 'like', "%{$search}%")
                  ->orWhereHas('customer', function ($customerQuery) use ($search) {
                      $customerQuery->where('name', 'like', "%{$search}%");
                  });
            });
        }

        // Customer filter
        if ($request->filled('customer')) {
            $query->where('customer_id', $request->customer);
        }

        // Status filter
        if ($request->filled('status')) {
            $query->where('status', $request->status);
        }

        // Date range filter
        if ($request->filled('date_from')) {
            $query->whereDate('sale_date', '>=', $request->date_from);
        }
        if ($request->filled('date_to')) {
            $query->whereDate('sale_date', '<=', $request->date_to);
        }

        // Payment method filter
        if ($request->filled('payment_method')) {
            $query->where('payment_method', $request->payment_method);
        }

        $sales = $query->orderBy('sale_date', 'desc')->paginate(15);
        $customers = Customer::where('is_active', true)->orderBy('name')->get();

        return view('finance.sales.index', compact('sales', 'customers'));
    }

    /**
     * Show the form for creating a new resource.
     */
    public function create()
    {
        $customers = Customer::where('is_active', true)->orderBy('name')->get();
        $products = Product::where('is_active', true)->where('stock_quantity', '>', 0)->orderBy('name')->get();
        
        // Generate next invoice number for display (using same logic as model)
        $datePrefix = date('Ymd');
        $todayCount = Sale::whereDate('created_at', today())->count();
        $nextNumber = $todayCount + 1;
        $invoiceNumber = 'INV-' . $datePrefix . '-' . str_pad($nextNumber, 4, '0', STR_PAD_LEFT);

        // Get current user's business profile for payment info
        $businessProfile = auth()->user()->businessProfile;

        return view('finance.sales.create', compact('customers', 'products', 'invoiceNumber', 'businessProfile'));
    }

    /**
     * Store a newly created resource in storage.
     */
    public function store(Request $request)
    {
        $validated = $request->validate([
            'customer_id' => 'nullable|exists:customers,id',
            'sale_date' => 'required|date',
            'payment_method' => 'required|in:cash,credit_card,debit_card,bank_transfer,e_wallet,qris',
            'notes' => 'nullable|string',
            'products' => 'required|array|min:1',
            'products.*.product_id' => 'required|exists:products,id',
            'products.*.quantity' => 'required|integer|min:1',
            'products.*.unit_price' => 'required|numeric|min:0',
            'products.*.discount_percentage' => 'nullable|numeric|min:0|max:100',
        ]);

        // Validate stock availability before processing
        foreach ($validated['products'] as $item) {
            $product = Product::find($item['product_id']);
            if (!$product || !$product->hasSufficientStock($item['quantity'])) {
                return back()->withErrors([
                    'products' => "Insufficient stock for product: " . ($product->name ?? 'Unknown') . ". Available: " . ($product->stock_quantity ?? 0) . ", Required: " . $item['quantity']
                ])->withInput();
            }
        }

        DB::transaction(function () use ($validated) {
            // Calculate totals first
            $subtotalAmount = 0;
            $totalDiscount = 0;

            foreach ($validated['products'] as $item) {
                $lineTotal = $item['quantity'] * $item['unit_price'];
                $discountPercentage = $item['discount_percentage'] ?? 0;
                $itemDiscount = $lineTotal * ($discountPercentage / 100);
                $subtotalAmount += $lineTotal - $itemDiscount;
                $totalDiscount += $itemDiscount;
            }

            $taxAmount = $subtotalAmount * 0.1; // 10% tax
            $totalAmount = $subtotalAmount + $taxAmount;

            // Create sale with all required fields (invoice number auto-generated by model)
            $sale = Sale::create([
                'customer_id' => $validated['customer_id'],
                'sale_date' => $validated['sale_date'],
                'subtotal' => $subtotalAmount,
                'tax_amount' => $taxAmount,
                'discount_amount' => $totalDiscount,
                'total_amount' => $totalAmount,
                'payment_method' => $validated['payment_method'],
                'status' => 'completed',
                'notes' => $validated['notes'],
            ]);

            // Create sale details and update stock
            foreach ($validated['products'] as $item) {
                $lineTotal = $item['quantity'] * $item['unit_price'];
                $discountPercentage = $item['discount_percentage'] ?? 0;
                $discountAmount = $lineTotal * ($discountPercentage / 100);

                SalesDetail::create([
                    'sale_id' => $sale->id,
                    'product_id' => $item['product_id'],
                    'quantity' => $item['quantity'],
                    'unit_price' => $item['unit_price'],
                    'discount_percentage' => $discountPercentage,
                    'discount_amount' => $discountAmount,
                    'line_total' => $lineTotal - $discountAmount,
                ]);

                // Safely update product stock
                $product = Product::find($item['product_id']);
                if (!$product->reduceStock($item['quantity'])) {
                    throw new \Exception("Failed to reduce stock for product: {$product->name}");
                }
            }

            // Update customer statistics (only if customer is specified, not walk-in)
            if (!empty($validated['customer_id'])) {
                $customer = Customer::find($validated['customer_id']);
                if ($customer) {
                    $customer->increment('total_spent', $totalAmount);
                    $customer->increment('purchase_frequency');
                    $customer->update(['last_purchase_date' => $validated['sale_date']]);

                    // CRM: Award loyalty points
                    $loyaltyProgram = \App\Models\CustomerLoyaltyProgram::active()->first();
                    if ($loyaltyProgram) {
                        $points = $loyaltyProgram->calculatePointsForAmount($totalAmount);
                        
                        $loyaltyPoints = $customer->loyaltyPoints;
                        if ($loyaltyPoints) {
                            $loyaltyPoints->addPoints($points, 'Purchase ' . $sale->invoice_number);
                        } else {
                            // Create loyalty points record if doesn't exist
                            \App\Models\CustomerLoyaltyPoint::create([
                                'customer_id' => $customer->id,
                                'loyalty_program_id' => $loyaltyProgram->id,
                                'points_earned' => $points,
                                'current_balance' => $points,
                                'tier_level' => 'bronze',
                                'last_earned_at' => now(),
                            ]);
                        }
                    }
                }
            }
        });

        return redirect()->route('finance.sales.index')
            ->with('success', 'Sale created successfully.');
    }

    /**
     * Display the specified resource.
     */
    public function show(Sale $sale)
    {
        // Load sales details with product (including soft deleted products)
        $sale->load(['customer', 'salesDetails' => function ($query) {
            $query->with(['product' => function ($q) {
                $q->withTrashed(); // Include soft deleted products
            }]);
        }]);
        
        // Get current user's business profile for payment info display
        $businessProfile = auth()->user()->businessProfile;
        
        return view('finance.sales.show', compact('sale', 'businessProfile'));
    }

    /**
     * Show the form for editing the specified resource.
     */
    public function edit(Sale $sale)
    {
        // Load sales details with product (including soft deleted products)
        $sale->load(['salesDetails' => function ($query) {
            $query->with(['product' => function ($q) {
                $q->withTrashed(); // Include soft deleted products
            }]);
        }]);
        
        $customers = Customer::where('is_active', true)->orderBy('name')->get();
        $products = Product::where('is_active', true)->orderBy('name')->get();

        // Get current user's business profile for payment info
        $businessProfile = auth()->user()->businessProfile;

        return view('finance.sales.edit', compact('sale', 'customers', 'products', 'businessProfile'));
    }

    /**
     * Update the specified resource in storage.
     */
    public function update(Request $request, Sale $sale)
    {
        $validated = $request->validate([
            'customer_id' => 'nullable|exists:customers,id',
            'sale_date' => 'required|date',
            'payment_method' => 'required|in:cash,credit_card,debit_card,bank_transfer,e_wallet,qris',
            'status' => 'required|in:pending,completed,cancelled,refunded',
            'notes' => 'nullable|string',
        ]);

        $sale->update($validated);

        return redirect()->route('finance.sales.show', $sale)
            ->with('success', 'Sale updated successfully.');
    }

    /**
     * Remove the specified resource from storage.
     */
    public function destroy(Sale $sale)
    {
        DB::transaction(function () use ($sale) {
            // Restore product stock
            foreach ($sale->salesDetails as $detail) {
                $product = Product::find($detail->product_id);
                if ($product) {
                    $product->increaseStock($detail->quantity);
                }
            }

            // Update customer statistics (only if customer exists, not walk-in)
            if ($sale->customer) {
                $customer = $sale->customer;
                $customer->decrement('total_spent', $sale->total_amount);
                $customer->decrement('purchase_frequency');
            }

            // Delete sale (soft delete)
            $sale->delete();
        });

        return redirect()->route('finance.sales.index')
            ->with('success', 'Sale deleted successfully.');
    }

    /**
     * Print invoice for the specified sale.
     */
    public function print(Sale $sale)
    {
        // Load sales details with product (including soft deleted products)
        $sale->load(['customer', 'salesDetails' => function ($query) {
            $query->with(['product' => function ($q) {
                $q->withTrashed(); // Include soft deleted products
            }]);
        }, 'creator']);
        
        // Get current user's business profile for payment info display
        $businessProfile = auth()->user()->businessProfile;
        
        return view('finance.sales.print', compact('sale', 'businessProfile'));
    }
}


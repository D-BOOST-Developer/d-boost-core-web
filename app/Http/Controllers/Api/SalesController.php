<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\Sale;
use App\Models\SalesDetail;

use App\Models\Product;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Database\QueryException;

class SalesController extends Controller
{
    /**
     * Get list of sales with optional filters
     */
    public function index(Request $request)
    {
        $query = Sale::with(['salesDetails.product'])
            ->orderBy('sale_date', 'desc')
            ->orderBy('created_at', 'desc');

        // Filter by status
        if ($request->filled('status')) {
            $query->where('status', $request->status);
        }

        // Filter by payment method
        if ($request->filled('payment_method')) {
            $query->where('payment_method', $request->payment_method);
        }

        // Filter by date range
        if ($request->filled('date_from')) {
            $query->whereDate('sale_date', '>=', $request->date_from);
        }
        if ($request->filled('date_to')) {
            $query->whereDate('sale_date', '<=', $request->date_to);
        }

        // Search by invoice number
        if ($request->filled('search')) {
            $search = $request->search;
            $query->where(function ($q) use ($search) {
                $q->where('invoice_number', 'like', "%{$search}%");
            });
        }

        $sales = $query->paginate($request->get('per_page', 20));

        return response()->json([
            'data' => $sales->items(),
            'meta' => [
                'current_page' => $sales->currentPage(),
                'last_page' => $sales->lastPage(),
                'per_page' => $sales->perPage(),
                'total' => $sales->total(),
            ]
        ]);
    }

    /**
     * Get single sale with details
     */
    public function show($id)
    {
        $sale = Sale::with(['salesDetails.product'])->findOrFail($id);
        return response()->json($sale);
    }

    /**
     * Store a new sale
     */
    public function store(Request $request)
    {
        $validated = $request->validate([

            'sale_date' => 'required|date',
            'payment_method' => 'required|in:cash,credit_card,debit_card,bank_transfer,e_wallet,qris',
            'notes' => 'nullable|string',
            'products' => 'required|array|min:1',
            'products.*.product_id' => 'required|exists:products,id',
            'products.*.quantity' => 'required|integer|min:1',
            'products.*.unit_price' => 'required|numeric|min:0',
            'products.*.discount_percentage' => 'nullable|numeric|min:0|max:100',
        ]);

        // Validate stock availability
        foreach ($validated['products'] as $item) {
            $product = Product::find($item['product_id']);
            if (!$product || !$product->hasSufficientStock($item['quantity'])) {
                return response()->json([
                    'message' => "Insufficient stock for product: " . ($product ? $product->name : 'Unknown'),
                    'errors' => [
                        'products' => ["Available: " . ($product ? $product->stock_quantity : 0) . ", Required: " . $item['quantity']]
                    ]
                ], 422);
            }
        }

        $maxRetries = 3;
        $attempt = 0;
        $sale = null;

        while ($attempt < $maxRetries) {
            try {
                $sale = DB::transaction(function () use ($validated) {
                    // Calculate totals
                    $subtotalAmount = 0;
                    $totalDiscount = 0;

                    foreach ($validated['products'] as $item) {
                        $lineTotal = $item['quantity'] * $item['unit_price'];
                        $discountPercentage = $item['discount_percentage'] ?? 0;
                        $itemDiscount = $lineTotal * ($discountPercentage / 100);
                        $subtotalAmount += $lineTotal - $itemDiscount;
                        $totalDiscount += $itemDiscount;
                    }

                    $taxAmount = $subtotalAmount * 0.1; // 10% tax
                    $totalAmount = $subtotalAmount + $taxAmount;

                    // Create sale (invoice number is auto-generated by model)
                    $sale = Sale::create([
                        'customer_id' => null,
                        'sale_date' => $validated['sale_date'],
                        'subtotal' => $subtotalAmount,
                        'tax_amount' => $taxAmount,
                        'discount_amount' => $totalDiscount,
                        'total_amount' => $totalAmount,
                        'payment_method' => $validated['payment_method'],
                        'status' => 'completed',
                        'notes' => $validated['notes'],
                    ]);

                    // Create sale details and update stock
                    foreach ($validated['products'] as $item) {
                        $lineTotal = $item['quantity'] * $item['unit_price'];
                        $discountPercentage = $item['discount_percentage'] ?? 0;
                        $discountAmount = $lineTotal * ($discountPercentage / 100);

                        SalesDetail::create([
                            'sale_id' => $sale->id,
                            'product_id' => $item['product_id'],
                            'quantity' => $item['quantity'],
                            'unit_price' => $item['unit_price'],
                            'discount_percentage' => $discountPercentage,
                            'discount_amount' => $discountAmount,
                            'line_total' => $lineTotal - $discountAmount,
                        ]);

                        // Reduce stock
                        $product = Product::find($item['product_id']);
                        $product->reduceStock($item['quantity']);
                    }

                    return $sale;
                });

                // Success - break out of retry loop
                break;

            } catch (QueryException $e) {
                // Check if it's a duplicate key error for invoice_number
                $errorMessage = $e->getMessage();
                $errorCode = $e->getCode();
                $isDuplicateKey = $errorCode == '23505' 
                    || str_contains($errorMessage, 'duplicate key value violates unique constraint')
                    || str_contains($errorMessage, 'invoice_number_unique')
                    || str_contains($errorMessage, 'invoice_number');
                
                if ($isDuplicateKey) {
                    $attempt++;
                    if ($attempt >= $maxRetries) {
                        return response()->json([
                            'message' => 'Failed to create sale: Unable to generate unique invoice number after multiple attempts. Please try again.',
                            'error' => 'Invoice number generation conflict'
                        ], 500);
                    }
                    // Wait a bit before retrying (with random jitter to avoid thundering herd)
                    usleep(rand(100000, 500000)); // 100-500ms
                    continue; // Retry
                }
                // If it's a different error, re-throw it
                throw $e;
            } catch (\Exception $e) {
                return response()->json([
                    'message' => 'Failed to create sale',
                    'error' => $e->getMessage()
                ], 500);
            }
        }

        if ($sale) {
            return response()->json([
                'message' => 'Sale created successfully',
                'data' => $sale->load(['salesDetails.product'])
            ], 201);
        }

        return response()->json([
            'message' => 'Failed to create sale after multiple attempts',
            'error' => 'Unknown error'
        ], 500);
    }

    /**
     * Update sale status
     */
    public function update(Request $request, $id)
    {
        $sale = Sale::findOrFail($id);

        $validated = $request->validate([
            'status' => 'sometimes|in:pending,completed,cancelled,refunded',
            'notes' => 'sometimes|nullable|string',
        ]);

        $sale->update($validated);

        return response()->json([
            'message' => 'Sale updated successfully',
            'data' => $sale->fresh(['salesDetails.product'])
        ]);
    }

    /**
     * Delete a sale
     */
    public function destroy($id)
    {
        $sale = Sale::findOrFail($id);

        try {
            DB::transaction(function () use ($sale) {
                // Restore stock for each item
                foreach ($sale->salesDetails as $detail) {
                    $product = Product::find($detail->product_id);
                    if ($product) {
                        $product->increment('stock_quantity', $detail->quantity);
                    }
                }

                // Delete sale details
                $sale->salesDetails()->delete();
                
                // Delete sale
                $sale->delete();
            });

            return response()->json([
                'message' => 'Sale deleted successfully'
            ]);

        } catch (\Exception $e) {
            return response()->json([
                'message' => 'Failed to delete sale',
                'error' => $e->getMessage()
            ], 500);
        }
    }

    /**
     * Get products for sale picker
     */
    public function products()
    {
        $products = Product::where('is_active', true)
            ->where('stock_quantity', '>', 0)
            ->select(['id', 'name', 'price', 'cost', 'stock_quantity', 'sku', 'category'])
            ->orderBy('name')
            ->get();

        return response()->json($products);
    }

    /**
     * Generate next invoice number
     */
    public function invoiceNumber()
    {
        $prefix = 'INV-' . date('Ymd') . '-';
        $lastSale = Sale::where('invoice_number', 'like', $prefix . '%')
            ->orderBy('invoice_number', 'desc')
            ->first();

        if ($lastSale) {
            $lastNumber = (int) substr($lastSale->invoice_number, -4);
            $nextNumber = str_pad($lastNumber + 1, 4, '0', STR_PAD_LEFT);
        } else {
            $nextNumber = '0001';
        }

        return response()->json([
            'invoice_number' => $prefix . $nextNumber
        ]);
    }
}
